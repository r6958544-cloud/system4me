-- ---------------------------------------------------------------------
-- Точки расширения для сторонних аддонов (например army_job), чтобы
-- добавлять свои профессии/вкладки в это же F4-меню, не изменяя
-- job_selector каждый раз:
--
--   PermissionCheckers[key]       -> function(): bool          (клиент)
--       Определяет, показывать ли строку профессии с
--       requiresPermission == key в списке "Профессия".
--
--   ServerPermissionCheckers[key] -> function(ply): bool        (сервер)
--       Финальная (авторитетная) проверка допуска перед тем,
--       как разрешить выбрать профессию с requiresPermission == key.
--
--   OnJobSelected[jobId]          -> function(ply)               (сервер)
--       Вызывается вместо стандартной выдачи оружия для профессий
--       с custom == true — сторонний аддон сам решает, что делать
--       (спавн, оружие, модель и т.д.). НЕ вызывается, если переход
--       на эту профессию сопровождается убийством (см. KillOnTransitionJobs
--       ниже) — в этом случае экипировку применит обычный респавн.
--
--   OnJobPrepare[jobId]           -> function(ply)               (сервер)
--       Вызывается ВСЕГДА при переходе на эту профессию, даже если
--       игрока в этот момент убивают, а не применяют экипировку сразу
--       (см. KillOnTransitionJobs). Для лёгких действий, которые обязаны
--       случиться именно в момент выбора, пока жив прошлый персонаж —
--       например, сохранить модель/бодигруппы до их смены.
--
--   OnJobLeft[jobId]              -> function(ply, newJob)        (сервер)
--       Вызывается, когда игрок уходит с профессии jobId на другую
--       (newJob). Например, для отмены эффектов профессии (вернуть
--       модель/бодигруппы, которые были до входа в неё).
--
--   ExtraTabs[]                   -> { id, label, visible(), build(panel) } (клиент)
--       Дополнительные вкладки в меню, показываются между
--       "Навигатор" и "Инфо", если visible() вернёт true.
--
--   JobChangeBlockers[key]        -> function(ply): reason string | nil (сервер)
--       Полная блокировка смены ЛЮБОЙ профессии (не конкретной, а
--       вообще любого выбора в меню). Если функция вернула непустую
--       строку — смена отклоняется, игроку показывается эта причина.
--       Например, используется тюрьмой: пока игрок сидит, он не может
--       сменить профессию вообще.
-- ---------------------------------------------------------------------
JobSelector.PermissionCheckers       = JobSelector.PermissionCheckers or {}
JobSelector.ServerPermissionCheckers = JobSelector.ServerPermissionCheckers or {}
JobSelector.OnJobSelected            = JobSelector.OnJobSelected or {}
JobSelector.OnJobPrepare             = JobSelector.OnJobPrepare or {}
JobSelector.OnJobLeft                = JobSelector.OnJobLeft or {}
JobSelector.ExtraTabs                = JobSelector.ExtraTabs or {}
JobSelector.JobChangeBlockers        = JobSelector.JobChangeBlockers or {}

-- ---------------------------------------------------------------------
-- Профессии, вход на которые ИЛИ уход с которых (с/на ЛЮБУЮ другую
-- профессию) сначала убивает игрока, а не применяет новую экипировку/
-- спавн сразу — новая профессия применится сама, через обычный цикл
-- респавна (PlayerSpawn/PlayerLoadout), точно так же, как это
-- происходит при обычной смерти.
-- ---------------------------------------------------------------------
JobSelector.KillOnTransitionJobs = {
    army = true,
}

-- Убивать ли игрока при переходе oldJob -> newJob: да, если хотя бы
-- одна из двух профессий помечена в KillOnTransitionJobs.
function JobSelector.ShouldKillOnTransition(oldJob, newJob)
    return JobSelector.KillOnTransitionJobs[oldJob] == true
        or JobSelector.KillOnTransitionJobs[newJob] == true
end

